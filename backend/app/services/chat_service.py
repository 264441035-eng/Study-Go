"""
チャット機能のサービス層。

現在はモックとして固定的な返答を返す。
将来的にAmazon Bedrockを利用したAI処理へ置き換える。
"""

def generate_reply(message: str) -> str:
    """
    通常のチャットメッセージに対する返答。
    タスク後の「2回目の詳しい回答」はここに入ってくるため、ここでボーナスを出す。
    """
    # ユーザーが追加で「グラフ」や「軸」など詳しい説明をしてくれた場合
    if "グラフ" in message or "軸" in message or "変形" in message:
        return (
            "大正解！「グラフを描くために頂点や軸を求める」という一番重要なポイントが、"
            "自分の言葉でしっかり説明できてるね。"
            "バッチリ理解できているから、ボーナスポイントGET！"
        )
        
    if "二次関数" in message:
        return "二次関数について勉強したんだね！偉い！"
    
    return "なるほど！もう少し教えてくれるかな？"


def generate_question(today_content: str) -> str:
    """
    今日の学習内容から問題を出す（最初のヒアリング後に呼ばれる）。
    """
    if "二次関数" in today_content:
        return (
            "二次関数を勉強したんだね、お疲れ様！"
            "じゃあ復習として一つ教えてほしいな。"
            "二次関数でよく使う「平方完成」って、そもそも何のためにする計算だったか説明できる？"
        )
    
    return (
        "今日勉強した内容で、一番重要だと思ったポイントを私に教えて！"
    )


def generate_feedback(explanation: str) -> str:
    """
    ユーザーの説明（1回目の回答）に対するフィードバック。
    ここでは一旦「もう一息！」と返し、詳細な説明（ボーナス）へ誘導する。
    """
    if "頂点" in explanation:
        return (
            "正解！でも、もう一息！"
            "頂点の座標が分かると、二次関数の「何」を描くときに役に立つんだっけ？"
            "自分の言葉でもう少しだけ詳しく教えて！"
        )
            
    return (
        "うーん、惜しいかも！"
        "どういうときに使う計算なのか、もう少し詳しく教えてくれないかな？"
    )